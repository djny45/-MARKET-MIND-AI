"""Governed static landing-page generator for agent-authored content.

This renders validated page content supplied by an agent/task into a self-contained
HTML page. It does not execute generated JavaScript or publish/deploy the page.
"""
from __future__ import annotations

from html import escape
from urllib.parse import urlparse

from .workers import list_workers

WORKER_IDS = {worker["id"] for worker in list_workers()}
MAX_SECTIONS = 12


def _text(value: str, field: str, limit: int, *, optional: bool = False) -> str:
    if value is None and optional:
        return ""
    if not isinstance(value, str) or (not optional and not value.strip()) or len(value) > limit:
        raise ValueError(f"{field} must be {'empty or ' if optional else ''}a string of at most {limit} characters")
    return value.strip()


def _safe_url(value: str) -> str:
    value = _text(value, "cta_url", 500, optional=True)
    if not value:
        return ""
    parsed = urlparse(value)
    if parsed.scheme not in {"https", "http"} or not parsed.netloc:
        raise ValueError("cta_url must be an absolute http or https URL")
    return value


def build_landing_page(worker_id: str, request: dict) -> dict:
    if worker_id not in WORKER_IDS:
        raise ValueError("worker_id must identify a registered agent")
    if not isinstance(request, dict):
        raise ValueError("page request must be an object")

    title = _text(request.get("title"), "title", 120)
    subtitle = _text(request.get("subtitle", ""), "subtitle", 300, optional=True)
    description = _text(request.get("description", ""), "description", 1200, optional=True)
    brand = _text(request.get("brand", "MARKET-MIND"), "brand", 80, optional=True) or "MARKET-MIND"
    theme = request.get("theme", "amber")
    themes = {
        "amber": ("#f59e0b", "#0b0d10", "#f5f5f5"),
        "blue": ("#60a5fa", "#07111f", "#f1f5f9"),
        "violet": ("#a78bfa", "#100b1c", "#f5f3ff"),
        "emerald": ("#34d399", "#071510", "#ecfdf5"),
    }
    if theme not in themes:
        raise ValueError("theme must be amber, blue, violet, or emerald")
    sections = request.get("sections", [])
    if not isinstance(sections, list) or len(sections) > MAX_SECTIONS:
        raise ValueError(f"sections must be a list of at most {MAX_SECTIONS} items")
    parsed_sections = []
    for index, section in enumerate(sections):
        if not isinstance(section, dict):
            raise ValueError(f"sections[{index}] must be an object")
        heading = _text(section.get("heading"), f"sections[{index}].heading", 120)
        body = _text(section.get("body"), f"sections[{index}].body", 2000)
        parsed_sections.append((heading, body))
    cta_label = _text(request.get("cta_label", ""), "cta_label", 80, optional=True)
    cta_url = _safe_url(request.get("cta_url", ""))
    accent, background, foreground = themes[theme]
    safe_brand, safe_title = escape(brand), escape(title)
    safe_subtitle, safe_description = escape(subtitle), escape(description)
    cards = "".join(
        f'<section class="card"><h2>{escape(heading)}</h2><p>{escape(body)}</p></section>'
        for heading, body in parsed_sections
    )
    cta = ""
    if cta_label and cta_url:
        cta = f'<a class="cta" href="{escape(cta_url, quote=True)}" rel="noopener noreferrer">{escape(cta_label)}</a>'
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="description" content="{safe_description}">
<title>{safe_title}</title>
<style>
:root{{--accent:{accent};--bg:{background};--fg:{foreground}}}
*{{box-sizing:border-box}}body{{margin:0;background:radial-gradient(ellipse at top,var(--accent)18,transparent 55%),var(--bg);color:var(--fg);font:16px/1.6 system-ui,sans-serif}}
main{{max-width:980px;margin:auto;padding:64px 24px}}header{{padding:56px 0}}.brand{{color:var(--accent);letter-spacing:.16em;text-transform:uppercase;font-size:.8rem}}
h1{{font-size:clamp(2.4rem,7vw,5rem);line-height:1.05;max-width:850px;margin:.5em 0}}.subtitle{{font-size:1.25rem;max-width:720px;color:#cbd5e1}}
.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(240px,1fr));gap:16px}}.card{{border:1px solid #ffffff20;border-radius:18px;padding:24px;background:#ffffff08}}.card h2{{color:var(--accent)}}.cta{{display:inline-block;margin-top:28px;padding:14px 22px;border-radius:999px;background:var(--accent);color:#111;text-decoration:none;font-weight:700}}footer{{margin-top:64px;color:#94a3b8;font-size:.8rem}}
</style></head><body><main><header><div class="brand">{safe_brand}</div><h1>{safe_title}</h1><p class="subtitle">{safe_subtitle}</p>{cta}</header><p>{safe_description}</p><div class="grid">{cards}</div><footer>Generated by MARKET-MIND-AI · Agent {escape(worker_id)} · Preview only</footer></main></body></html>"""
    return {
        "worker_id": worker_id,
        "title": title,
        "theme": theme,
        "sections_count": len(parsed_sections),
        "html": html,
        "format": "static_html",
        "published": False,
        "scripts_executed": False,
        "skill_used": "stageshow",
        "note": "Generated from supplied agent/task content. Preview or export; hosting/deployment is not included.",
    }
