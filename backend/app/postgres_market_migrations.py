"""Versioned PostgreSQL schema foundation for normalized market observations.

This migration is deliberately opt-in. It does not switch application stores
from SQLite; that requires a separate adapter/parity-test change.
"""
from __future__ import annotations

from typing import Any, Callable

from .postgres import database_url

MARKET_DATA_SCHEMA_VERSION = 1
_ADVISORY_LOCK_ID = 734821905

_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS market_bars (
        symbol TEXT NOT NULL,
        interval TEXT NOT NULL,
        timestamp TIMESTAMPTZ NOT NULL,
        open DOUBLE PRECISION NOT NULL,
        high DOUBLE PRECISION NOT NULL,
        low DOUBLE PRECISION NOT NULL,
        close DOUBLE PRECISION NOT NULL,
        volume DOUBLE PRECISION NOT NULL,
        status TEXT NOT NULL,
        source TEXT NOT NULL,
        retrieved_at TIMESTAMPTZ NOT NULL,
        PRIMARY KEY (symbol, interval, timestamp, source)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS market_ingestion_audit_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        event_type TEXT NOT NULL,
        symbol TEXT NOT NULL,
        interval TEXT NOT NULL,
        source TEXT NOT NULL,
        status TEXT NOT NULL,
        observation_count INTEGER NOT NULL CHECK (observation_count >= 0),
        first_timestamp TIMESTAMPTZ,
        last_timestamp TIMESTAMPTZ,
        occurred_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_market_bars_lookup
    ON market_bars (symbol, interval, timestamp DESC)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_market_audit_scope
    ON market_ingestion_audit_events (symbol, interval, id DESC)
    """,
)


def apply_market_data_schema(
    environ: dict[str, str] | None = None,
    *,
    connect: Callable[..., Any] | None = None,
) -> dict[str, Any]:
    """Apply the market-data schema transactionally; never expose the DSN."""
    dsn = database_url(environ)
    if not dsn:
        return {"status": "not_configured", "applied_version": 0}

    try:
        if connect is None:
            import psycopg
            connect = psycopg.connect

        with connect(dsn, connect_timeout=3) as connection:
            with connection.cursor() as cursor:
                cursor.execute("SELECT pg_advisory_xact_lock(%s)", (_ADVISORY_LOCK_ID,))
                cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS schema_migrations (
                        version INTEGER PRIMARY KEY,
                        applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """
                )
                cursor.execute(
                    "SELECT COALESCE(MAX(version), 0) FROM schema_migrations"
                )
                row = cursor.fetchone()
                current = int(row[0]) if row else 0
                if current > MARKET_DATA_SCHEMA_VERSION:
                    return {
                        "status": "schema_too_new",
                        "applied_version": current,
                        "expected_version": MARKET_DATA_SCHEMA_VERSION,
                    }
                if current < MARKET_DATA_SCHEMA_VERSION:
                    for statement in _STATEMENTS:
                        cursor.execute(statement)
                    cursor.execute(
                        "INSERT INTO schema_migrations (version) VALUES (%s)",
                        (MARKET_DATA_SCHEMA_VERSION,),
                    )
                    current = MARKET_DATA_SCHEMA_VERSION

        return {"status": "ready", "applied_version": current}
    except Exception as exc:
        return {
            "status": "not_ready",
            "applied_version": 0,
            "error_type": type(exc).__name__,
        }


__all__ = ["MARKET_DATA_SCHEMA_VERSION", "apply_market_data_schema"]
